#!/usr/bin/env python3
"""Generate fw/sha256/selftest_vectors.h from the vendored NIST CAVP vectors.

Reads third_party/nist_vectors/shabytetestvectors/SHA256ShortMsg.rsp and
SHA256LongMsg.rsp and emits 8 byte-oriented test vectors:
  empty, "abc", 55-byte, 56-byte, 64-byte (short), and 3 multi-block (long).

Usage: tools/gen_sha_vectors.py   (run from repo root)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHORT = ROOT / "third_party/nist_vectors/shabytetestvectors/SHA256ShortMsg.rsp"
LONG = ROOT / "third_party/nist_vectors/shabytetestvectors/SHA256LongMsg.rsp"
OUT = ROOT / "fw/sha256/selftest_vectors.h"

# (source file, bit length) for the 8 vectors
WANT = [
    (SHORT, 0),      # empty
    (SHORT, 24),     # "abc"
    (SHORT, 440),    # 55 bytes
    (SHORT, 448),    # 56 bytes
    (SHORT, 512),    # 64 bytes
    (LONG, 1304),    # 163 bytes, multi-block
    (LONG, 2096),    # 262 bytes, multi-block
    (LONG, 2888),    # 361 bytes, multi-block
]


def load(path):
    tests = {}
    cur = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if line.startswith("Len"):
            if cur:
                tests[cur["len"]] = cur
            cur = {"len": int(line.split("=")[1])}
        elif line.startswith("Msg"):
            cur["msg"] = line.split("=")[1].strip()
        elif line.startswith("MD"):
            cur["md"] = line.split("=")[1].strip()
    if cur:
        tests[cur["len"]] = cur
    return tests


def main():
    short = load(SHORT)
    long = load(LONG)
    vecs = []
    for path, bitlen in WANT:
        src = short if path == SHORT else long
        t = src[bitlen]
        nbytes = bitlen // 8
        msg = t["msg"]
        if bitlen == 0:
            assert msg == "00"  # CAVS convention: placeholder byte for empty
            msg = ""
        assert len(msg) == nbytes * 2, (bitlen, len(msg), nbytes)
        assert len(t["md"]) == 64
        vecs.append((nbytes, msg, t["md"], path.name, bitlen))

    lines = []
    lines.append("/* selftest_vectors.h — GENERATED by tools/gen_sha_vectors.py.")
    lines.append(" * Do not edit by hand. Source: NIST CAVP shabytetestvectors")
    lines.append(" * (SHA256ShortMsg.rsp / SHA256LongMsg.rsp, vendored in third_party).")
    lines.append(" * Embedded ONLY in the D2 boot self-test (contract-allowed). */")
    lines.append("#ifndef SELFTEST_VECTORS_H")
    lines.append("#define SELFTEST_VECTORS_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("typedef struct {")
    lines.append("    uint32_t len;")
    lines.append("    const uint8_t * msg;")
    lines.append("    const uint8_t * expect;")
    lines.append("} sha_selftest_vec_t;")
    lines.append("")
    for i, (nbytes, msg, md, src, bitlen) in enumerate(vecs):
        mbytes = ", ".join("0x" + msg[j:j + 2] for j in range(0, len(msg), 2))
        dbytes = ", ".join("0x" + md[j:j + 2] for j in range(0, len(md), 2))
        lines.append(f"/* vector {i}: {src} Len={bitlen} ({nbytes} bytes) */")
        lines.append(f"static const uint8_t sha_vec_msg_{i}[] = {{{mbytes if mbytes else ''}}};")
        lines.append(f"static const uint8_t sha_vec_md_{i}[] = {{{dbytes}}};")
        lines.append("")
    lines.append("static const sha_selftest_vec_t sha_selftest_vecs[] = {")
    for i, (nbytes, msg, md, src, bitlen) in enumerate(vecs):
        lines.append(f"    {{ {nbytes}U, sha_vec_msg_{i}, sha_vec_md_{i} }},")
    lines.append("};")
    lines.append("")
    lines.append("#define SHA_SELFTEST_NVECS \\")
    lines.append("    ( sizeof( sha_selftest_vecs ) / sizeof( sha_selftest_vecs[ 0 ] ) )")
    lines.append("")
    lines.append("#endif /* SELFTEST_VECTORS_H */")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(vecs)} vectors)")


if __name__ == "__main__":
    main()
