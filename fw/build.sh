#!/usr/bin/env bash
# fw/build.sh — build all Muse MCU firmware images.
#
# Self-contained: if TOOLCHAIN is unset, sources env/activate.sh
# (written by env/setup.sh). Builds fw/build/<app>.{elf,hex} for every
# app in APPS via fw/Makefile.
#
# Usage: bash fw/build.sh
set -u
ROOT="$(cd "$(dirname "$0")/.." && pwd)"

if [ -z "${TOOLCHAIN:-}" ] && [ -f "$ROOT/env/activate.sh" ]; then
  # shellcheck disable=SC1091
  source "$ROOT/env/activate.sh"
fi
if [ -z "${TOOLCHAIN:-}" ] || [ ! -x "$TOOLCHAIN/riscv-none-elf-gcc" ]; then
  echo "build.sh: no working RISC-V toolchain (run env/setup.sh first)" >&2
  exit 1
fi

APPS="hello uart_rx_test spi_test timer_gpio_test pingpong rtos_regtest rtos_queue rtos_sema rtos_notify rtos_timer rtos_isr rtos_blocktim preempt_test app_demo"

FAIL=0
for a in $APPS; do
  echo "build.sh: APP=$a"
  if ! make -C "$ROOT/fw" APP="$a"; then FAIL=1; fi
done

if [ "$FAIL" != 0 ]; then echo "build.sh: FAIL"; exit 1; fi
echo "build.sh: ALL OK ($(echo "$APPS" | wc -w | tr -d ' ') apps)"

# A8 SPI flash image: 256-byte deterministic PRBS (tb/tb_spi.sv loads it
# with $readmemh and compares byte-for-byte, so content only needs to be
# deterministic, not meaningful).
echo "build.sh: spi_img.hex (A8)"
python3 "$ROOT/tb/stub_fw/gen_spi_img.py" "$ROOT/fw/build/spi_img.bin" >/dev/null
python3 -c "
data = open('$ROOT/fw/build/spi_img.bin','rb').read()
assert len(data) == 256
with open('$ROOT/fw/build/spi_img.hex','w') as f:
    f.write('\n'.join('%02x' % b for b in data) + '\n')
"
# flash.hex is the demo workload image (D1/D2/F2); generated by tools/gen_flash.py
# (NOT the 256-byte A8 SPI test pattern).
echo "build.sh: flash.hex (D1/D2)"
python3 "$ROOT/tools/gen_flash.py" --seed 1 --out "$ROOT/fw/build/flash.bin" >/dev/null
python3 -c "
data = open('$ROOT/fw/build/flash.bin','rb').read()
with open('$ROOT/fw/build/flash.hex','w') as f:
    f.write('\n'.join('%02x' % b for b in data) + '\n')
"
echo "build.sh: flash.hex OK"

# Arch-test images + Spike goldens (A1/A2): tools/build_arch.py writes
# fw/build/arch/<name>.hex (consumed by tb/run_arch.sh) and the golden
# signatures in results/raw/arch/. Nothing else in the automation
# produced these, so a fresh tree failed A1/A2 for missing inputs.
echo "build.sh: arch-test images + Spike goldens (A1/A2)"
python3 "$ROOT/tools/build_arch.py" || { echo "build.sh: FAIL build_arch"; exit 1; }

# Testbench mini-programs (A3-A6): tb/build/<name>.hex consumed by
# tb/run_reset.sh, tb/run_trap.sh, tb/run_irq.sh, tb/run_memmap.sh.
# Same gap as above: mini_build.sh existed but nothing called it.
echo "build.sh: tb mini-programs (A3-A6)"
for p in reset trap irq memmap; do
  MMCU="$ROOT" TOOLCHAIN="$TOOLCHAIN" bash "$ROOT/tb/mini_build.sh" "$p" \
    || { echo "build.sh: FAIL mini_build $p"; exit 1; }
done
echo "build.sh: tb mini-programs OK"
